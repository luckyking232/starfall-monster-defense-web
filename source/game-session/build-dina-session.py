"""Produce the opt-in coordinator from the exact earlier /1 receipt, not a fork of game rules."""
import argparse
import hashlib
from pathlib import Path

here = Path(__file__).resolve().parent
original = (here / "session.mjs").read_bytes()
assert hashlib.sha256(original).hexdigest() == "c55197fafaf76e1f7600b71e9bef835117305f09dfa57e2e5ef9e07025247d20"
s = original.decode()
replacements = [
    ("import {makeStage1Client,STAGE1_PROTOCOL} from '../browser-stage1/client.mjs';",
     """import {makeVerifiedDinaClient, DINA_STAGE1_PROTOCOL as STAGE1_PROTOCOL,
  verifyDinaDescribe,verifyDinaGates,asLegacyChoiceInput} from './dina-transport.mjs';"""),
    ("export async function openGameSession(", "export async function openDinaGameSession("),
    ("  let clockFrames=0;", "  let clockFrames=0, workerGates=null;"),
    ("mode:'private-offline',stageId:", "mode:'private-offline',lane:'dina-v2',workerProtocol:STAGE1_PROTOCOL,stageId:"),
    ("revision,scope,\n", "revision,scope,workerGates,\n"),
    ("    return message;\n  }\n  function accept", "    verifyDinaGates(message,true);\n    return message;\n  }\n  function accept"),
    ("    if(sendToHud) hud.accept(message);", "    if(sendToHud) hud.accept(asLegacyChoiceInput(message));\n    workerGates=immutable(message.gates);"),
    ("clockFrames=0;events=[];", "clockFrames=0;workerGates=null;events=[];"),
    ("client=makeStage1Client({WorkerClass});", "client=makeVerifiedDinaClient({WorkerClass});"),
    ("        const ready=verify(await handle.start(rng),'ready',token);", """        verifyDinaDescribe(await handle.describe());
        const ready=verify(await handle.start(rng),'ready',token);"""),
    ("          return reply;", "          return asLegacyChoiceInput(reply);"),
    ("result=null;settlement=null;runId=null;requestId=0;events=[];", "result=null;settlement=null;runId=null;requestId=0;workerGates=null;events=[];"),
]
for old,new in replacements:
    assert s.count(old)==1, old
    s=s.replace(old,new)
s="// Generated by build-dina-session.py from pinned session.mjs. Do not edit this derivative.\n"+s
ap=argparse.ArgumentParser()
ap.add_argument("--verify",action="store_true")
arg=ap.parse_args()
out=here/"session-dina.mjs"
if arg.verify:
    assert out.read_bytes()==s.encode(), "Dina coordinator drift"
else:
    out.write_bytes(s.encode())
